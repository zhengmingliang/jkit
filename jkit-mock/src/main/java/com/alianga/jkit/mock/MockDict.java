    /** 行政区划节点：省 / 市 / 县三级共用一个结构。 */
    public static final class Region {
        private final String name;
        private final List<Region> children;

        Region(String name, List<Region> children) {
            this.name = name;
            this.children = children;
        }

        /**
         * 节点名称。
         *
         * @return 名称
         */
        public String getName() {
            return name;
        }

        /**
         * 下级节点，县节点为空列表。
         *
         * @return 子节点
         */
        public List<Region> getChildren() {
            return children;
        }
    }

    private static volatile List<Region> tree;

    /**
     * 省 / 市 / 县三级行政区划树，首次调用时构建并缓存。
     *
     * @return 省级节点列表
     */
    public static List<Region> regionTree() {
        if (tree == null) {
            synchronized (MockDict.class) {
                if (tree == null) {
                    tree = buildTree();
                }
            }
        }
        return tree;
    }

    private static List<Region> buildTree() {
        List<Region> provinces = new ArrayList<Region>();
        int cityIndex = 0;
        for (int i = 0; i < PROVINCES.length; i++) {
            List<Region> cities = new ArrayList<Region>();
            for (String city : split(CITIES[i])) {
                List<Region> counties = new ArrayList<Region>();
                if (cityIndex < COUNTIES.length) {
                    for (String c : split(COUNTIES[cityIndex])) {
                        counties.add(new Region(c, Collections.<Region>emptyList()));
                    }
                }
                cityIndex++;
                cities.add(new Region(city, counties));
            }
            provinces.add(new Region(PROVINCES[i], cities));
        }
        return provinces;
    }

    private static String[] split(String line) {
        if (line == null || line.isEmpty()) {
            return new String[0];
        }
        return line.split(",");
    }

